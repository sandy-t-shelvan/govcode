package ato

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"time"
)

const Disclaimer = "CONTRACTOR SELF-ASSESSMENT - NOT AN AUTHORIZATION. Generated by govcode; the ISSM/ISSO and assessor must verify every statement."

// FuzzTargets are the fuzz targets CI runs on every pull request (30 s each,
// scripts/ci/fuzz.sh). TestFuzzTargetsListed keeps this list complete.
var FuzzTargets = []string{
	"FuzzAllowlisted", "FuzzDecideNeverAllowsMeta", "FuzzExtractToolCalls", "FuzzFormat", "FuzzJailResolve",
	"FuzzLoad", "FuzzNonStreamReply", "FuzzOutline", "FuzzRepairJSON", "FuzzScan", "FuzzScanDiff", "FuzzServeInput", "FuzzSniff",
	"FuzzValidateArgs", "FuzzVerifyAttestation", "FuzzVerifyGarbage",
}

// Inputs is everything the package is built from. Optional parts are nil.
type Inputs struct {
	Version        string
	Classification string
	Host           string
	Now            time.Time
	Policy         map[string]any   // selected settings, no secrets
	Preflight      []map[string]any // name/status/detail
	Benchmark      *Benchmark
	Site           *SiteRuleMap
	VEX            map[string]any
	VEXSummary     *VEXSummary
	Tests          *TestSummary
	AuditSample    []map[string]any
}

// Write builds the package in dir and returns the files written. dir must
// not exist or be empty, so an old package is never mixed with a new one.
func Write(dir string, in Inputs) ([]string, error) {
	if es, err := os.ReadDir(dir); err == nil && len(es) > 0 {
		return nil, fmt.Errorf("%s is not empty", dir)
	}
	if err := os.MkdirAll(dir, 0o750); err != nil {
		return nil, err
	}
	banner := in.Classification
	if banner == "" {
		banner = "CLASSIFICATION NOT SET - mark before release"
	}
	var files []string
	put := func(name string, v any) error {
		var b []byte
		switch x := v.(type) {
		case string:
			b = []byte(x)
		default:
			var err error
			if b, err = json.MarshalIndent(x, "", "  "); err != nil {
				return err
			}
			b = append(b, '\n')
		}
		p := filepath.Join(dir, name)
		os.MkdirAll(filepath.Dir(p), 0o750)
		if err := os.WriteFile(p, b, 0o640); err != nil {
			return err
		}
		files = append(files, name)
		return nil
	}
	head := func(kind string) map[string]any {
		return map[string]any{"schema": "govcode.ato." + kind + "/v1", "classification": banner, "disclaimer": Disclaimer,
			"govcode_version": in.Version, "generated": in.Now.UTC().Format(time.RFC3339)}
	}

	ctl := head("controls")
	ctl["catalog"] = "NIST SP 800-53 Rev. 5"
	ctl["controls"] = Controls
	if err := put("controls.json", ctl); err != nil {
		return nil, err
	}
	dw := head("dowi")
	dw["instruction"] = "DoWI 8430.01 Accelerated Mission Software (effective 2026-09-08)"
	dw["caution"] = "Requirement wording is from secondary summaries, not the official text; verify each row against the published instruction."
	dw["mapping"] = DoWI
	if err := put("dowi-8430.01.json", dw); err != nil {
		return nil, err
	}
	cn := head("cnssi1253")
	cn["note"] = "govcode is an application component. Its controls support, and do not replace, the CNSSI 1253 baseline the AO selects for the host system (typically Moderate/Moderate/Moderate or higher for SECRET, with the Classified Information overlay). The controls in controls.json are offered for inheritance into that baseline; host controls (IA-2 authentication, physical, media, personnel) remain the system's."
	if err := put("cnssi-1253.json", cn); err != nil {
		return nil, err
	}
	if in.Policy != nil {
		pc := head("configuration")
		pc["policy"] = in.Policy
		pc["preflight"] = in.Preflight
		if err := put("configuration.json", pc); err != nil {
			return nil, err
		}
	}
	var stigLine string
	if in.Benchmark != nil {
		ck, ev, st, err := CKLB(in.Benchmark, in.Site, in.Host)
		if err != nil {
			return nil, err
		}
		if err := put("stig/"+safeName(in.Benchmark.ID)+".cklb", ck); err != nil {
			return nil, err
		}
		stigLine = fmt.Sprintf("%s %s (%s): %d rules; evidence pointers on %d; site statuses on %d; all others not_reviewed.",
			in.Benchmark.Title, in.Benchmark.Version, in.Benchmark.Release, len(in.Benchmark.Rules), ev, st)
	} else {
		stigLine = "not generated: pass -stig with the official ASD STIG XCCDF from DISA (govcode ships no STIG content)."
	}
	vexLine := "not generated: pass -govulncheck with `govulncheck -json ./...` output."
	if in.VEX != nil {
		if err := put("vex.openvex.json", in.VEX); err != nil {
			return nil, err
		}
		s := in.VEXSummary
		vexLine = fmt.Sprintf("%s, vulndb %s: %d affected, %d not affected (vulnerable code not called).", s.Scanner, s.DB, s.Affected, s.NotAffected)
	}
	testLine := "not included: pass -test-json with `go test -json ./...` output."
	if in.Tests != nil {
		ts := head("tests")
		ts["results"] = in.Tests
		ts["fuzz_targets"] = FuzzTargets
		ts["fuzz_policy"] = "every target runs 30 s per pull request in CI; crashers are committed as regression inputs"
		if err := put("tests.json", ts); err != nil {
			return nil, err
		}
		testLine = fmt.Sprintf("%d passed, %d failed, %d skipped across %d packages; %d fuzz targets.", in.Tests.Passed, in.Tests.Failed, in.Tests.Skipped, len(in.Tests.Packages), len(FuzzTargets))
	}
	auditLine := "not included (no policy loaded)."
	if in.AuditSample != nil {
		as := head("audit-sample")
		as["handling"] = "Audit summaries are classified at the level of the code they record: " + banner
		as["entries"] = in.AuditSample
		if err := put("audit-sample.json", as); err != nil {
			return nil, err
		}
		auditLine = fmt.Sprintf("%d most recent entries (summaries only; no objects).", len(in.AuditSample))
	}

	var md strings.Builder
	fmt.Fprintf(&md, "**%s**\n\n# govcode ATO evidence package\n\n> %s\n\n", banner, Disclaimer)
	fmt.Fprintf(&md, "govcode %s, generated %s on %s.\n\n", in.Version, in.Now.UTC().Format(time.RFC3339), in.Host)
	md.WriteString("| Part | File | Status |\n|---|---|---|\n")
	fmt.Fprintf(&md, "| NIST SP 800-53 Rev 5 statements | controls.json | %d controls |\n", len(Controls))
	fmt.Fprintf(&md, "| DoWI 8430.01 mapping | dowi-8430.01.json | %d rows (verify wording against the official text) |\n", len(DoWI))
	md.WriteString("| CNSSI 1253 note | cnssi-1253.json | component controls for inheritance |\n")
	fmt.Fprintf(&md, "| ASD STIG checklist | stig/*.cklb | %s |\n", stigLine)
	fmt.Fprintf(&md, "| VEX | vex.openvex.json | %s |\n", vexLine)
	fmt.Fprintf(&md, "| Tests and fuzzing | tests.json | %s |\n", testLine)
	fmt.Fprintf(&md, "| Audit sample | audit-sample.json | %s |\n", auditLine)
	if in.Policy != nil {
		md.WriteString("| Configuration and preflight | configuration.json | policy settings and every preflight result |\n")
	}
	md.WriteString("\n## Controls\n\n| Control | Title | Status | Customer responsibility |\n|---|---|---|---|\n")
	for _, c := range Controls {
		fmt.Fprintf(&md, "| %s | %s | %s | %s |\n", c.ID, c.Title, c.Status, c.Customer)
	}
	fmt.Fprintf(&md, "\n**%s**\n", banner)
	if err := put("README.md", md.String()); err != nil {
		return nil, err
	}

	sort.Strings(files)
	var man strings.Builder
	for _, f := range files {
		b, _ := os.ReadFile(filepath.Join(dir, f))
		s := sha256.Sum256(b)
		fmt.Fprintf(&man, "%s  %s\n", hex.EncodeToString(s[:]), f)
	}
	if err := put("SHA256SUMS", man.String()); err != nil {
		return nil, err
	}
	return files, nil
}

func safeName(s string) string {
	s = strings.Map(func(r rune) rune {
		if r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' || r == '-' || r == '_' || r == '.' {
			return r
		}
		return '_'
	}, s)
	if s == "" {
		return "stig"
	}
	return s
}
